/**
 * Runs the REAL @contentauth/c2pa-node library end to end (sign → read back → tamper → read again) by executing
 * scripts/c2pa-real-check.ts in plain Node — the library is an ES module + native addon that jest cannot load.
 * Skipped automatically where the binary cannot load (Node < 22.12, musl/Alpine); the fake-engine specs still run there.
 */
import { execFileSync } from 'node:child_process';
import { createPrivateKey, X509Certificate } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { DIGITAL_SOURCE_TRAINED_ALGORITHMIC_MEDIA } from './c2pa-engine';
import { getEphemeralSigningIdentity, resetEphemeralSigningIdentity } from './ephemeral-cert';

function runReal(): any {
  try {
    const out = execFileSync(process.execPath, ['-r', 'ts-node/register/transpile-only', path.join(__dirname, '../../../scripts/c2pa-real-check.ts')], {
      cwd: path.join(__dirname, '../../..'),
      encoding: 'utf8',
      timeout: 120_000,
    });
    return JSON.parse(out.trim().split('\n').pop()!);
  } catch (err) {
    return { available: false, reason: `check script failed: ${String((err as any)?.message ?? err).slice(0, 300)}`, crashed: true };
  }
}
const real = runReal();
const maybe = real.available ? describe : describe.skip;

describe('ephemeral dev signing identity', () => {
  it('is a valid ECDSA P-256 chain: CA-signed leaf, digitalSignature, document-signing EKU; no key material is a constant', async () => {
    const id = await getEphemeralSigningIdentity();
    const [leafPem, caPem] = id.certChainPem.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g)!;
    const leaf = new X509Certificate(leafPem);
    const ca = new X509Certificate(caPem);
    expect(leaf.checkIssued(ca)).toBe(true);
    expect(leaf.verify(ca.publicKey)).toBe(true);
    expect(ca.verify(ca.publicKey)).toBe(true);
    expect(ca.ca).toBe(true);
    expect(leaf.ca).toBe(false);
    expect(leaf.keyUsage).toEqual(expect.arrayContaining(['1.3.6.1.5.5.7.3.4', '1.3.6.1.5.5.7.3.36']));
    expect(leaf.subject).toMatch(/ephemeral/);
    expect(createPrivateKey(id.privateKeyPem).asymmetricKeyType).toBe('ec');
    expect(new Date(leaf.validTo).getTime() - Date.now()).toBeLessThan(31 * 86_400_000);
  });
  it('is generated once per process and regenerated after a reset', async () => {
    const a = await getEphemeralSigningIdentity();
    expect(await getEphemeralSigningIdentity()).toBe(a);
    resetEphemeralSigningIdentity();
    expect((await getEphemeralSigningIdentity()).privateKeyPem).not.toBe(a.privateKeyPem);
  });
  it('the source tree contains no private key (keys come from config only)', () => {
    const dir = __dirname;
    for (const f of fs.readdirSync(dir)) {
      if (f.endsWith('.spec.ts')) continue; // this file mentions the marker text
      expect(fs.readFileSync(path.join(dir, f), 'utf8')).not.toMatch(/-----BEGIN (EC |RSA )?PRIVATE KEY-----\s*\n[A-Za-z0-9+/=]{40,}/);
    }
  });
});

maybe('real c2pa engine (via scripts/c2pa-real-check.ts)', () => {
  it('the check script ran without crashing', () => {
    expect(real.crashed).toBeUndefined();
  });

  it.each(['image/jpeg', 'image/png', 'image/webp', 'video/mp4'])('signs %s and the credential reads back as AI-generated + valid', (mime) => {
    const f = real.formats[mime];
    const kind = mime.startsWith('video') ? 'video' : 'image';
    expect(f.before.hasManifest).toBe(false);
    expect(f.grew).toBe(true);
    expect(f.after).toMatchObject({ hasManifest: true, valid: true, aiGenerated: true, digitalSourceType: DIGITAL_SOURCE_TRAINED_ALGORITHMIC_MEDIA, claimGenerator: 'ContentFlow', errors: [] });
    expect(f.disclosure).toMatchObject({ ai_generated: true, media_type: kind, model: 'nano-banana-pro', provider: 'fal', label: '[This content was generated by AI]' });
    // the dev signer is (rightly) not on a trust list:
    expect(f.rawErrors).toContain('signingCredential.untrusted');
    expect(f.signer).toBe('ephemeral-dev');
  });

  it('detects tampering: changing the image after signing invalidates the credential', () => {
    expect(real.tampered.valid).toBe(false);
  });

  it('uses a configured PEM certificate + key (from env) and reports signer=configured', () => {
    expect(real.configured).toMatchObject({ signer: 'configured', keyType: 'ec', verify: { valid: true, aiGenerated: true } });
  });

  it('attachToGeneratedMedia end to end: download → sign → store → the stored bytes verify', () => {
    expect(real.attach.c2pa).toMatchObject({ signed: true, signer: 'ephemeral-dev' });
    expect(real.attach.verify).toMatchObject({ valid: true, aiGenerated: true });
  });
});
