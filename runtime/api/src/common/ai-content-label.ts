/**
 * AI 生成内容标识（AIGC labeling）统一工具。
 *
 * 依据《人工智能生成合成内容标识办法》的要求分两层：
 *  - 显式标识：文本内容附带用户可见的「AI 生成」提示；
 *  - 隐式标识：媒体文件元数据中写入 AI 生成标记。
 *
 * 生成/导出链路统一从这里取标识，避免各处自造文案不一致。
 */

/** 文本显式标识（前缀形式，便于导出内容一眼可辨） */
export const AI_TEXT_LABEL = '【本内容由 AI 生成】';

/** International edition label (MARKET_REGION=global): the whole international UI and API is English. */
export const AI_TEXT_LABEL_EN = '[This content was generated by AI]';

/** The visible label for the current market. */
export function aiTextLabel(env: NodeJS.ProcessEnv = process.env): string {
  return env.MARKET_REGION === 'global' ? AI_TEXT_LABEL_EN : AI_TEXT_LABEL;
}

/** 隐式标识写入元数据时使用的生成方名称 */
export const AI_GENERATOR_NAME = '分发侠';
/** International edition product name (no Chinese in international payloads). */
export const AI_GENERATOR_NAME_EN = 'ContentFlow';

/**
 * 给 AI 生成的文本加显式标识。幂等：已带标识的内容不会重复添加。
 */
export function labelAiGeneratedText(content: string, label: string = aiTextLabel()): string {
  const body = (content || '').trim();
  // Idempotent across markets: content labelled in either language is not labelled twice.
  if (body.startsWith(label) || body.startsWith(AI_TEXT_LABEL) || body.startsWith(AI_TEXT_LABEL_EN)) return body;
  return body.length > 0 ? `${label}\n${body}` : label;
}

export interface AiMediaMetadata {
  /** 隐式标识核心字段：标记该媒体为 AI 生成 */
  ai_generated: true;
  /** 生成方 */
  generator: string;
  /** 媒体类型：image / video / audio 等 */
  media_type: string;
  /** 生成时间（ISO 8601） */
  generated_at: string;
  /** 生成所用模型（可选，未知则不伪造） */
  model?: string;
  /**
   * 服务提供者编码（GB 45438-2025 隐式标识要素；如统一社会信用代码）。
   * 从环境变量 AIGC_PROVIDER_CODE 读取；未配置时为空字符串（不编造），启动时会提示。
   */
  provider_code: string;
  /** 内容编号：已保存的内容用 Content.id；尚未保存时用生成记录编号；都没有则为空字符串。 */
  content_id: string;
}

/** 隐式标识里的服务提供者编码：只从环境变量读，未配置返回空字符串。 */
export function aigcProviderCode(env: NodeJS.ProcessEnv = process.env): string {
  return String(env.AIGC_PROVIDER_CODE ?? '').trim();
}

/**
 * 构建媒体文件的 AI 生成隐式标识元数据，
 * 供导出图片/视频时写入文件元数据或随响应下发。
 */
export function buildAiMediaMetadata(opts: {
  mediaType: string;
  model?: string;
  generator?: string;
  now?: Date;
  contentId?: string | null;
  providerCode?: string;
}): AiMediaMetadata {
  const meta: AiMediaMetadata = {
    ai_generated: true,
    generator: opts.generator || (process.env.MARKET_REGION === 'global' ? AI_GENERATOR_NAME_EN : AI_GENERATOR_NAME),
    media_type: opts.mediaType,
    generated_at: (opts.now || new Date()).toISOString(),
    provider_code: opts.providerCode ?? aigcProviderCode(),
    content_id: String(opts.contentId ?? ''),
  };
  if (opts.model) meta.model = opts.model;
  return meta;
}
