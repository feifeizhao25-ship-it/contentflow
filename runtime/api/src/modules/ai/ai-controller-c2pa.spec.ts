/**
 * EU AI Act Art. 50(2): generated images carry a signed C2PA manifest, and the API hands out that signed copy.
 * Real configureApp + real routes (generate/image and GET /ai/media/:file); only the login guard, the AI provider,
 * the provider download and the native C2PA engine are replaced.
 */
import { ExecutionContext, INestApplication } from '@nestjs/common';
import { Test } from '@nestjs/testing';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
// eslint-disable-next-line @typescript-eslint/no-var-requires
const request = require('supertest');
import { configureApp } from '../../bootstrap';
import { C2PA_ENGINE, C2paEngine, C2paSignRequest } from '../../common/provenance/c2pa-engine';
import { MediaController } from '../../common/provenance/media.controller';
import { ProvenanceService } from '../../common/provenance/provenance.service';
import { body, fixture } from '../../common/provenance/test-fixtures';
import { JwtAuthGuard } from '../../common/guards/jwt-auth.guard';
import { AIController } from './ai.controller';
import { AIService } from './ai.service';
import { AiAllowanceService } from './ai-allowance.service';
import { ComplianceService } from './compliance.service';
import { finalizeReservedResponse, UsageService } from '../system/usage.service';

const MARK = Buffer.from('::C2PA::');
class FakeEngine implements C2paEngine {
  requests: C2paSignRequest[] = [];
  fail = false;
  unavailableReason() { return null; }
  async sign(req: C2paSignRequest) {
    if (this.fail) throw new Error('signer down');
    this.requests.push(req);
    return Buffer.concat([req.buffer, MARK]);
  }
  async read() { return { hasManifest: false, validationErrors: [] }; }
}

describe('generate/image with C2PA Content Credentials', () => {
  let app: INestApplication;
  let dir: string;
  const engine = new FakeEngine();
  const ai = { assertTenantDailyBudget: jest.fn(), generateImage: jest.fn(), recordGeneration: jest.fn() };
  const usage = { withAiHold: jest.fn(), saved: [] as Array<{ generation?: { outputContent?: string } }> };
  const saved = { ...process.env };
  const realFetch = global.fetch;

  beforeEach(async () => {
    jest.resetAllMocks();
    engine.requests = [];
    engine.fail = false;
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cf-c2pa-ctl-'));
    process.env = { ...saved, MARKET_REGION: 'global', NODE_ENV: 'test', MEDIA_STORE_DIR: dir };
    delete process.env.C2PA_ENABLED;
    usage.saved = [];
    usage.withAiHold.mockImplementation(async (_i: unknown, run: () => Promise<any>) => {
      const produced = await run();
      usage.saved.push(produced);
      return finalizeReservedResponse(produced, 'gen-1');
    });
    ai.assertTenantDailyBudget.mockResolvedValue(undefined);
    ai.generateImage.mockResolvedValue({ url: 'https://93.184.216.34/out.png', provider: 'fal', model: 'nano-banana-pro' });
    global.fetch = jest.fn(async () => new Response(body(fixture('image/png')))) as any;
    const moduleRef = await Test.createTestingModule({
      controllers: [AIController, MediaController],
      providers: [
        { provide: AIService, useValue: ai },
        { provide: UsageService, useValue: usage },
        AiAllowanceService,
        ComplianceService,
        ProvenanceService,
        { provide: C2PA_ENGINE, useValue: engine },
      ],
    })
      .overrideGuard(JwtAuthGuard)
      .useValue({ canActivate: (ctx: ExecutionContext) => { ctx.switchToHttp().getRequest().user = { id: 'u', sub: 'u', tenantId: 't', role: 'owner' }; return true; } })
      .compile();
    app = moduleRef.createNestApplication();
    configureApp(app, []);
    await app.init();
    jest.spyOn(app.get(ProvenanceService)['logger'], 'error').mockImplementation(() => undefined);
    jest.spyOn(app.get(ProvenanceService)['logger'], 'warn').mockImplementation(() => undefined);
  });
  afterEach(async () => {
    process.env = { ...saved };
    global.fetch = realFetch;
    await app.close();
    fs.rmSync(dir, { recursive: true, force: true });
  });

  const generate = () => request(app.getHttpServer()).post('/api/v1/ai/generate/image').send({ prompt: 'a cup of coffee' });

  it('global edition: returns the signed copy plus the visible label, text-style metadata and the C2PA disclosure', async () => {
    const res = await generate();
    expect(res.status).toBe(201);
    const d = res.body.data;
    expect(d.url).toMatch(/^\/api\/v1\/ai\/media\/[a-f0-9]{32}\.png$/);
    expect(d.providerUrl).toBe('https://93.184.216.34/out.png');
    expect(d).toMatchObject({
      aiGenerated: true,
      aiLabel: '[This content was generated by AI]',
      aiMetadata: { ai_generated: true, media_type: 'image', content_id: 'gen-1' },
      c2pa: { standard: 'C2PA', signed: true, signer: 'ephemeral-dev', digitalSourceType: 'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia' },
    });
    expect(engine.requests[0]).toMatchObject({ mimeType: 'image/png', digitalSourceType: expect.stringMatching(/trainedAlgorithmicMedia$/) });
    // the saved generation record points at what the user actually received
    expect(usage.saved[0].generation?.outputContent).toBe(d.url);
  });

  it('the returned url serves the signed file (raw bytes, image type, nosniff, cacheable), not wrapped in the JSON envelope', async () => {
    const d = (await generate()).body.data;
    const file = await request(app.getHttpServer()).get(d.url).buffer(true).parse((res: any, cb: any) => {
      const chunks: Buffer[] = [];
      res.on('data', (c: Buffer) => chunks.push(c));
      res.on('end', () => cb(null, Buffer.concat(chunks)));
    });
    expect(file.status).toBe(200);
    expect(file.headers['content-type']).toMatch(/^image\/png/);
    expect(file.headers['x-content-type-options']).toBe('nosniff');
    expect(file.headers['cache-control']).toMatch(/max-age=86400/);
    expect(file.body.subarray(file.body.length - MARK.length).equals(MARK)).toBe(true);
    expect(file.body.subarray(0, 8).equals(fixture('image/png').subarray(0, 8))).toBe(true);
  });

  it('media route: unknown, malformed and traversal names are 404 and need no login', async () => {
    for (const name of [`${'0'.repeat(32)}.png`, 'x.png', '..%2f..%2fetc%2fpasswd', `${'a'.repeat(32)}.php`]) {
      expect((await request(app.getHttpServer()).get(`/api/v1/ai/media/${name}`)).status).toBe(404);
    }
  });

  it('signing failure never breaks generation: original url, c2pa.signed=false with the reason, label and metadata intact', async () => {
    engine.fail = true;
    const res = await generate();
    expect(res.status).toBe(201);
    expect(res.body.data).toMatchObject({
      url: 'https://93.184.216.34/out.png',
      aiGenerated: true,
      aiLabel: '[This content was generated by AI]',
      aiMetadata: { ai_generated: true, media_type: 'image' },
      c2pa: { signed: false, reason: 'signer down' },
    });
  });

  it('download failure (provider host on a private address) also fails open', async () => {
    ai.generateImage.mockResolvedValue({ url: 'https://192.168.1.10/out.png', provider: 'fal', model: 'm' });
    const res = await generate();
    expect(res.body.data).toMatchObject({ url: 'https://192.168.1.10/out.png', c2pa: { signed: false, reason: expect.stringMatching(/not public/) } });
  });

  it('CN edition: off by default — provider url returned untouched, no c2pa field, no download', async () => {
    process.env.MARKET_REGION = 'cn';
    const res = await generate();
    expect(res.body.data.url).toBe('https://93.184.216.34/out.png');
    expect(res.body.data.c2pa).toBeUndefined();
    expect(global.fetch).not.toHaveBeenCalled();
  });

  it('feature flag: C2PA_ENABLED=false switches it off in the global edition; =true switches it on in CN', async () => {
    process.env.C2PA_ENABLED = 'false';
    expect((await generate()).body.data.c2pa).toBeUndefined();
    process.env.MARKET_REGION = 'cn';
    process.env.C2PA_ENABLED = 'true';
    expect((await generate()).body.data.c2pa).toMatchObject({ signed: true });
  });
});
