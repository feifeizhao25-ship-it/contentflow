-- 计算用户等级
CREATE OR REPLACE FUNCTION calculate_user_level(exp_points INT)
RETURNS INT AS $$
BEGIN
    RETURN FLOOR(SQRT(exp_points / 100)) + 1;
END;
$$ LANGUAGE plpgsql;

-- 添加经验值并更新等级
CREATE OR REPLACE FUNCTION add_experience_points(user_uuid UUID, points INT)
RETURNS VOID AS $$
BEGIN
    UPDATE user_gamification
    SET experience_points = experience_points + points,
        level = calculate_user_level(experience_points + points),
        updated_at = NOW()
    WHERE user_id = user_uuid;
END;
$$ LANGUAGE plpgsql;

-- 检查并更新连续活跃天数
CREATE OR REPLACE FUNCTION update_streak_days(user_uuid UUID)
RETURNS VOID AS $$
DECLARE
    last_active DATE;
    current_streak INT;
BEGIN
    SELECT last_active_date, streak_days INTO last_active, current_streak
    FROM user_gamification WHERE user_id = user_uuid;

    IF last_active IS NULL THEN
        UPDATE user_gamification SET streak_days = 1, last_active_date = CURRENT_DATE WHERE user_id = user_uuid;
    ELSIF last_active = CURRENT_DATE - 1 THEN
        UPDATE user_gamification SET streak_days = current_streak + 1, last_active_date = CURRENT_DATE WHERE user_id = user_uuid;
    ELSIF last_active < CURRENT_DATE - 1 THEN
        UPDATE user_gamification SET streak_days = 1, last_active_date = CURRENT_DATE WHERE user_id = user_uuid;
    END IF;
END;
$$ LANGUAGE plpgsql;

