-- =====================================================
-- 分发侠 (ContentFlow) Phase 4 新功能数据库架构
-- 创建日期: 2026-01-10
-- =====================================================

-- 1. 增长目标设定表
CREATE TABLE IF NOT EXISTS growth_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    target_type VARCHAR(50) NOT NULL, -- 'followers', 'views', 'engagement', 'revenue'
    target_value BIGINT NOT NULL,
    period_type VARCHAR(20) NOT NULL DEFAULT 'monthly', -- 'weekly', 'monthly', 'quarterly', 'yearly'
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    current_value BIGINT DEFAULT 0,
    status VARCHAR(20) DEFAULT 'active', -- 'active', 'completed', 'failed'
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 内容标注表（用于爆款拆解）
CREATE TABLE IF NOT EXISTS content_annotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    content_id UUID, -- 关联 contents 表
    source_url TEXT,
    source_platform VARCHAR(50),
    annotation_type VARCHAR(50) NOT NULL, -- 'hook', 'structure', 'emotion', 'keyword', 'template'
    annotation_data JSONB NOT NULL,
    ai_analysis_result TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 人设模板表
CREATE TABLE IF NOT EXISTS persona_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    is_system_template BOOLEAN DEFAULT FALSE,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(50) NOT NULL, -- 'knowledge', 'lifestyle', 'entertainment', 'education', etc.
    description TEXT,
    tone_of_voice TEXT, -- 语气风格描述
    typical_topics TEXT[], -- 典型话题类型
    writing_examples TEXT[], -- 写作范例
    template_config JSONB, -- AI 生成时的配置参数
    usage_count INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. 账号健康度记录表
CREATE TABLE IF NOT EXISTS account_health (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    check_date DATE NOT NULL,
    health_score INT DEFAULT 100, -- 0-100
    status VARCHAR(20) DEFAULT 'healthy', -- 'healthy', 'warning', 'limited', 'banned'
    issues JSONB, -- 检测到的问题列表
    recommendations JSONB, -- 改善建议
    metrics_snapshot JSONB, -- 当时的指标快照
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. 用户通知表（每日推送记录）
CREATE TABLE IF NOT EXISTS user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    notification_type VARCHAR(50) NOT NULL, -- 'daily_digest', 'hot_topic', 'content_alert', 'milestone'
    title VARCHAR(200) NOT NULL,
    content TEXT,
    metadata JSONB,
    is_read BOOLEAN DEFAULT FALSE,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. A/B 测试表
CREATE TABLE IF NOT EXISTS ab_tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    content_id UUID REFERENCES contents(id) ON DELETE CASCADE,
    test_name VARCHAR(200) NOT NULL,
    variants JSONB NOT NULL, -- { "A": {content: "...", impressions: 0, clicks: 0}, "B": {...} }
    winner_variant VARCHAR(10),
    status VARCHAR(20) DEFAULT 'running', -- 'running', 'completed', 'paused'
    start_date TIMESTAMPTZ DEFAULT NOW(),
    end_date TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. 竞品监控表
CREATE TABLE IF NOT EXISTS competitor_monitors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    competitor_name VARCHAR(100) NOT NULL,
    competitor_platform VARCHAR(50) NOT NULL,
    account_url TEXT,
    last_checked_at TIMESTAMPTZ,
    last_post_date DATE,
    recent_posts JSONB, -- 最近发布的帖子数据
    engagement_stats JSONB, -- 互动统计数据
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, competitor_platform, account_url)
);

-- 8. 定时任务队列表（用于持久化）
CREATE TABLE IF NOT EXISTS scheduled_task_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type VARCHAR(50) NOT NULL, -- 'publish', 'notification', 'health_check'
    task_payload JSONB NOT NULL,
    scheduled_at TIMESTAMPTZ NOT NULL,
    executed_at TIMESTAMPTZ,
    status VARCHAR(20) DEFAULT 'pending', -- 'pending', 'processing', 'completed', 'failed'
    retry_count INT DEFAULT 0,
    error_message TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. 内容预测评分表
CREATE TABLE IF NOT EXISTS content_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id UUID REFERENCES contents(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    platform VARCHAR(50) NOT NULL,
    predicted_score INT, -- 1-100 预估热度分数
    factors JSONB, -- 评分因素 { "title": 30, "timing": 20, "topic": 25, ... }
    confidence DECIMAL(5,2), -- 置信度 0-1
    actual_performance JSONB, -- 实际发布后的表现数据
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. 用户成长体系表
CREATE TABLE IF NOT EXISTS user_gamification (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    level INT DEFAULT 1,
    experience_points INT DEFAULT 0,
    total_contents_created INT DEFAULT 0,
    total_published INT DEFAULT 0,
    streak_days INT DEFAULT 0, -- 连续发布天数
    last_active_date DATE,
    achievements JSONB DEFAULT '[]', -- 已获得的成就
    badges JSONB DEFAULT '[]',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

