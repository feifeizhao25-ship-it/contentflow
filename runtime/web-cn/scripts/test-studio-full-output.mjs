import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const out=process.env.EVIDENCE_DIR || '/tmp/studio-full-output';
await fs.mkdir(out,{recursive:true});
const body=Array.from({length:18},(_,i)=>`第${i+1}段：这是明确标记的接口测试正文，核对完整显示、手机换行与末段可见性。不能当成真实模型回答或专业建议。`).join('\n\n');
const prompts=Array.from({length:4},(_,i)=>`封面提示词${i+1}：完整展示这个测试提示词，不应静默丢弃。`);
const titles=['完整测试标题'.repeat(18),'第二个测试标题'];
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const checks=[];
try {for(const width of [390,1440]) {
 const ctx=await browser.newContext({viewport:{width,height:900}});await ctx.addCookies([{name:'ff_token',value:'FIXTURE_NOT_LOGIN',url:'http://127.0.0.1:3433'}]);
 const page=await ctx.newPage();const apis=[];let articles=0;
 await page.route('**/api/**',async route=>{const path=new URL(route.request().url()).pathname;let data={};
 if(path.endsWith('/accounts')) data=[];
 if(path.endsWith('/billing/subscription'))data={plan:'pro',aiTokens:{limit:50000,used:123,remaining:49877,imageTokenEquivalent:2500}};
 if(path.endsWith('/auth/me'))data={id:'fixture',name:'测试用户',role:'owner'};
 if(path.endsWith('/ai/generate/article'))data=++articles===1?{content:body,visualPrompts:prompts}:{};
 if(path.endsWith('/ai/generate/titles'))data={titles};
 apis.push({path,data,testFixture:true});await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({success:true,data})});});
 await page.goto('http://127.0.0.1:3433/studio?topic=完整输出测试',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'一键生成文案包'}).click();
 const area=page.getByPlaceholder('内容包生成后自动填充，可继续编辑');
 await page.waitForFunction(()=>document.querySelector('textarea[placeholder="内容包生成后自动填充，可继续编辑"]')?.value.includes('第18段'));
 await page.getByText(titles[1],{exact:true}).waitFor();
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:`${out}/${width}.png`,fullPage:true});
 await fs.writeFile(`${out}/${width}.txt`,await page.locator('body').innerText()+'\n\n【编辑框完整值】\n'+await area.inputValue());
 await fs.writeFile(`${out}/${width}.json`,JSON.stringify(apis,null,2));
 const size=await area.evaluate(el=>({client:el.clientHeight,scroll:el.scrollHeight}));
 const row={width,bodyEqual:(await area.inputValue())===body,fullHeight:size.scroll<=size.client+2,promptsVisible:await page.getByText(prompts[3],{exact:true}).count()===1,noOverflow:await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)};checks.push(row);
 await page.getByRole('button',{name:'一键生成文案包'}).click();
 await page.getByRole('alert').filter({hasText:'没有收到有效正文'}).waitFor();
 assert.equal(await area.inputValue(),body,'empty result must preserve previous full body');
 assert.equal(apis.filter(a=>a.path.endsWith('/ai/generate/titles')).length,1,'empty article must not trigger another title request');
 await fs.writeFile(`${out}/${width}-empty.json`,JSON.stringify(apis,null,2));
 await ctx.close();
}} finally {await browser.close();}
await fs.writeFile(`${out}/checks.json`,JSON.stringify(checks,null,2));
console.log(checks);
assert.ok(checks.every(r=>r.bodyEqual&&r.fullHeight&&r.promptsVisible&&r.noOverflow),'Full output must fit without clipping or omitted prompts');
